export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('en'); // 默认英文

  const raw = useCallback(
    (key: string): string | undefined => {
      if (key in translations[language]) return translations[language][key];
      if (key in translations.en) return translations.en[key];
      return undefined;
    },
    [language],
  );

  const t = useCallback((key: string): string => raw(key) || key, [raw]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, raw }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    // Fallback for when used outside LanguageProvider (e.g. Figma preview)
    const raw = (key: string) => translations.en[key];
    return {
      language: 'en' as Language,
      setLanguage: () => {},
      t: (key: string) => raw(key) || key,
      raw,
    };
  }
  return context;
}
